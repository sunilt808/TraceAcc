// Digital seal badge shown next to released reports.
function SealBadge({ report }) {
  const [seal, setSeal] = useState(null);

  useEffect(() => {
    if (!report.signature_hash) return;
    let alive = true;
    reportsAPI
      .verifySignature(report.id)
      .then((res) => {
        if (alive) setSeal(res);
      })
      .catch(() => {});
    return () => {
      alive = false;
    };
  }, [report.id, report.signature_hash]);

  if (!report.signature_hash || !seal) return null;

  return (
    <div
      style={{
        display: 'inline-flex',
        alignItems: 'center',
        gap: 6,
        padding: '3px 10px',
        borderRadius: 14,
        border: `1px solid ${seal.valid ? '#8957e5' : '#f85149'}`,
        background: seal.valid ? 'rgba(137, 87, 229, 0.12)' : 'rgba(248, 81, 73, 0.12)',
        fontSize: 11,
        fontWeight: 600,
        color: seal.valid ? '#d2a8ff' : '#ff7b72',
        marginTop: 6,
      }}
      title={
        seal.valid
          ? `Officially sealed · ${seal.seal_id} · signed by ${seal.signed_by} on ${new Date(seal.signed_at).toLocaleString()}`
          : seal.reason
      }
    >
      {seal.valid ? (
        <>
          <CheckCircleFill size={11} className="me-1" /> Officially Sealed
        </>
      ) : (
        <>
          <XCircleFill size={11} className="me-1" /> Seal Invalid — Contact Support
        </>
      )}
    </div>
  );
}

